export const getServiceBySlug = (slugOrId) => {
  if (!slugOrId) return null;
  const normalized = slugOrId.toLowerCase().trim();
  return (
    servicesData.find(
      (s) =>
        s.slug === normalized ||
        s.id === normalized ||
        s.aliases.includes(normalized)
    ) || null
  );
};
